import json
from enum import Enum

# менять только эти константы!!!
COMMANDS_FILE_PATH = "./commands.json"
ASM_TABLE_H_PATH = "./assembler/asm_table.h"
COMMAND_SWITCH_H_PATH = "./vm/command_switch.h"
COMMANDS_TABLE_H_PATH = "./vm/commands_table.h"
UNKNOWN_COMMAND_NUM = 1488

with open(COMMANDS_FILE_PATH) as file:
    data = json.load(file)

ArgTypes = Enum("ArgTypes", data["arg_types"])
ARG_TYPES = {e.name: e for e in ArgTypes}


def get_arg_type(value):
    if value is None:
        return ArgTypes.ATYPE_VOID
    try:
        return ARG_TYPES[value]
    except KeyError:
        raise ValueError(f"Unknown arg type in JSON: {value}")


def get_cmd_str(string):
    if string.startswith("PUSH"): 
        return "PUSH"
    if string.startswith("POP"): 
        return "POP"
    return string

def get_cmd_function(string):
    if string in ["JA", "JAE", "JB", "JBE", "JE", "JNE"]:
        return "ejmp_condition(vm)"
    return f"e{string.lower()}(vm)"


class Command:
    def __init__(self,
                 cmd_str,
                 cmd_num=0,
                 cmd_args_count=0,
                 arg1_type=ArgTypes.ATYPE_VOID,
                 arg2_type=ArgTypes.ATYPE_VOID):
        self.cmd_num = cmd_num
        self.cmd_str = cmd_str
        self.cmd_args_count = cmd_args_count
        self.arg1_type = arg1_type
        self.arg2_type = arg2_type


COMMANDS = []

for cmd in data["commands"]:
    command = Command(cmd_str=cmd.get("cmd_str", None), cmd_args_count=cmd.get("cmd_args_count", 0),
                      arg1_type=get_arg_type(cmd.get("arg1_type", None)),
                      arg2_type=get_arg_type(cmd.get("arg2_type", None)))
    COMMANDS.append(command)

N_COMMANDS = len(COMMANDS)

COMMANDS.sort(key=lambda x: x.cmd_str)

for i in range(N_COMMANDS):
    COMMANDS[i].cmd_num = i

with open(COMMANDS_TABLE_H_PATH, "w") as file:
    file.write("// THIS FILE WAS GENERATED BY generate_table.py\n\n")
    file.write("""#ifndef COMMANDS_TABLE_H
#define COMMANDS_TABLE_H

#include <stddef.h>\n\n""")

    file.write("enum Commands\n")
    file.write("{\n")
    for i in range(N_COMMANDS):
        file.write(f"\t{COMMANDS[i].cmd_str} = {COMMANDS[i].cmd_num},\n")
    file.write("};\n")
    file.write("\n")

    file.write("""struct Command
{
    enum Commands cmd;
    size_t cmd_args_count;
    long long arg1;
    long long arg2;
};\n\n""")

    file.write(f"const size_t N_COMMANDS = {N_COMMANDS};\n\n")
    file.write("const static struct Command commands[N_COMMANDS] = {\n")
    for i in range(N_COMMANDS):
        file.write(f"\t{{.cmd = {COMMANDS[i].cmd_str}, .cmd_args_count = {COMMANDS[i].cmd_args_count}}},\n")
    file.write("};\n\n")
    file.write("#endif // COMMANDS_TABLE_H\n")

with open(ASM_TABLE_H_PATH, "w") as file:
    file.write("// THIS FILE WAS GENERATED BY generate_table.py\n\n")
    file.write("""#ifndef ASM_TABLE_H
#define ASM_TABLE_H

#include <stddef.h>\n\n""")

    file.write("enum Commands\n")
    file.write("{\n")
    for i in range(N_COMMANDS):
        file.write(f"\t{COMMANDS[i].cmd_str} = {COMMANDS[i].cmd_num},\n")
    file.write(f"\n\tUNKNOWN = {UNKNOWN_COMMAND_NUM},\n")
    file.write("};\n")
    file.write("\n")

    file.write("enum ArgTypes\n")
    file.write("{\n")
    for i in range(len(ArgTypes)):
        file.write(f"\t{ArgTypes(i).name},\n")
    file.write("};\n")
    file.write("\n")

    file.write("""struct Command
{
    enum Commands cmd_num;
    const char *cmd_str;
    const size_t cmd_args_count;
    const enum ArgTypes arg1_type;
    const enum ArgTypes arg2_type;
};\n\n""")

    file.write(f"const size_t N_COMMANDS = {N_COMMANDS};\n\n")
    file.write("const static struct Command commands[N_COMMANDS] = {\n")
    for i in range(N_COMMANDS):
        file.write(f"""\t{{
        .cmd_num = {COMMANDS[i].cmd_str},
        .cmd_str = "{get_cmd_str(COMMANDS[i].cmd_str)}",
        .cmd_args_count = {COMMANDS[i].cmd_args_count},
        .arg1_type = {COMMANDS[i].arg1_type.name},
        .arg2_type = {COMMANDS[i].arg2_type.name},
    }},\n\n""")
    file.write("};\n\n")
    file.write("#endif // ASM_TABLE_H\n")

with open(COMMAND_SWITCH_H_PATH, "w") as file:
    file.write("// THIS FILE WAS GENERATED BY generate_table.py\n\n")
    file.write("""#ifndef COMMAND_SWITCH_H
#define COMMAND_SWITCH_H\n\n""")
    file.write("""ExecutorError execute_command(VM *vm)
{
    assert(vm);
    assert(vm->code);
    assert(vm->code_length);

    switch (vm->current_command.cmd)
    {\n""")
    for i in range(N_COMMANDS):
        file.write(f"\tcase {COMMANDS[i].cmd_str}:\n")
        file.write(f"\t\treturn {get_cmd_function(COMMANDS[i].cmd_str)};\n")
    file.write("""\tdefault:
        LOG("ERROR: unknown command while casing executing command");
        assert(0 && "ПРОИЗОШЕЛ ПОЛНЫЙ БЛЯЗДЕЦ");
    }
    return (ExecutorError){.stack_error = STACK_OK, .executor_error = EXECUTOR_OK};""")
    file.write("}\n\n")
    file.write("#endif // COMMAND_SWITCH_H\n")

